// 剪贴板历史：记住最近 10 条复制的文字，按快捷键（默认 ⌃⌥⌘V）弹出列表，可搜索；
// 点一条就把它放回剪贴板第一条，并粘贴到当前输入框。只在内存里，退出即清空；
// 密码管理器标记为「隐藏 / 临时」的内容不记录。

@MainActor
@Observable
final class ClipboardHistory {
    static let shared = ClipboardHistory()
    static let limit = 10
    static let enabledKey = "clipboardHistory.enabled"

    struct Item: Identifiable, Equatable {
        let id = UUID()
        let text: String
        let date: Date
        let app: String?
    }

    private(set) var items: [Item] = []
    @ObservationIgnored private var lastChange = NSPasteboard.general.changeCount
    @ObservationIgnored private var timer: Timer?

    /// 密码管理器等用这些类型标记不该被记录的内容（nspasteboard.org 约定）。
    private static let skipTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ]

    static var isEnabled: Bool { UserDefaults.standard.object(forKey: enabledKey) as? Bool ?? true }

    func start() {
        guard timer == nil else { return }
        lastChange = NSPasteboard.general.changeCount
        capture()   // 启动时剪贴板里已有的文字也算一条
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { _ in
            MainActor.assumeIsolated { ClipboardHistory.shared.poll() }
        }
    }

    func clear() { items.removeAll() }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        guard Self.isEnabled else { return }
        capture()
    }

    private func capture() {
        let pasteboard = NSPasteboard.general
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skipTypes),
              let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        let app = NSWorkspace.shared.frontmostApplication
        let name = app?.processIdentifier == ProcessInfo.processInfo.processIdentifier ? nil : app?.localizedName
        add(text, app: name)
    }

    private func add(_ text: String, app: String?) {
        items.removeAll { $0.text == text }
        items.insert(Item(text: text, date: Date(), app: app), at: 0)
        if items.count > Self.limit { items.removeLast(items.count - Self.limit) }
    }

    /// 把某一条放回剪贴板第一条。
    func promote(_ item: Item) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(item.text, forType: .string)
        lastChange = pasteboard.changeCount
        add(item.text, app: item.app)
    }

    func filtered(_ query: String) -> [Item] {
        let q = query.trimmingCharacters(in: .whitespaces)
        guard !q.isEmpty else { return items }
        return items.filter { $0.text.localizedCaseInsensitiveContains(q) }
    }
}

// MARK: - 弹出列表

private final class ClipboardPanel: NSPanel {
    var onEscape: (() -> Void)?
    override var canBecomeKey: Bool { true }
    override func cancelOperation(_ sender: Any?) { onEscape?() }
}

@MainActor
final class ClipboardPanelController {
    static let shared = ClipboardPanelController()

    private var panel: ClipboardPanel?
    private let model = ClipboardPanelModel()
    /// 打开列表时的前台应用，选完后粘贴回这里。
    private var targetApp: NSRunningApplication?

    func toggle() {
        if let panel, panel.isVisible { close(); return }
        show()
    }

    func show() {
        let me = ProcessInfo.processInfo.processIdentifier
        let front = NSWorkspace.shared.frontmostApplication
        targetApp = front?.processIdentifier == me ? nil : front
        let panel = self.panel ?? makePanel()
        self.panel = panel
        model.reset()
        let size = NSSize(width: 460, height: 420)
        let mouse = NSEvent.mouseLocation
        if let screen = NSScreen.screens.first(where: { $0.frame.contains(mouse) }) ?? NSScreen.main {
            let visible = screen.visibleFrame
            panel.setFrame(NSRect(x: visible.midX - size.width / 2,
                                  y: visible.maxY - visible.height * 0.2 - size.height,
                                  width: size.width, height: size.height), display: true)
        }
        panel.makeKeyAndOrderFront(nil)
    }

    func close() {
        panel?.orderOut(nil)
    }

    fileprivate func choose(_ item: ClipboardHistory.Item) {
        close()
        ClipboardHistory.shared.promote(item)
        guard let target = targetApp else {
            Toast.shared.show("已放回剪贴板第一条", seconds: 2)
            return
        }
        guard AXIsProcessTrusted() else {
            Toast.shared.show("已放回剪贴板第一条。需要「辅助功能」权限才能自动粘贴", style: .warning)
            return
        }
        Task {
            if NSWorkspace.shared.frontmostApplication?.processIdentifier != target.processIdentifier {
                target.activate()
            }
            _ = await KeySynth.waitForRelease(timeout: 1.5)
            try? await Task.sleep(for: .milliseconds(80))
            KeySynth.press(kVK_ANSI_V)
        }
    }

    private func makePanel() -> ClipboardPanel {
        let panel = ClipboardPanel(contentRect: NSRect(x: 0, y: 0, width: 460, height: 420),
                                   styleMask: [.borderless, .nonactivatingPanel],
                                   backing: .buffered, defer: false)
        panel.isOpaque = false
        panel.backgroundColor = .clear
        panel.hasShadow = true
        panel.isFloatingPanel = true
        panel.level = .floating
        panel.hidesOnDeactivate = false
        panel.isReleasedWhenClosed = false
        panel.collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary]
        panel.onEscape = { [weak self] in self?.close() }
        let root = ClipboardListView(model: model,
                                     onChoose: { [weak self] in self?.choose($0) },
                                     onClose: { [weak self] in self?.close() })
            .clipShape(RoundedRectangle(cornerRadius: 12, style: .continuous))
            .overlay(RoundedRectangle(cornerRadius: 12, style: .continuous)
                .strokeBorder(Color.primary.opacity(0.12), lineWidth: 0.5))
        let host = NSHostingView(rootView: root)
        host.sizingOptions = []
        panel.contentView = host
        // 失去焦点（点了别处）就收起
        NotificationCenter.default.addObserver(forName: NSWindow.didResignKeyNotification, object: panel, queue: .main) { _ in
            MainActor.assumeIsolated { ClipboardPanelController.shared.close() }
        }
        return panel
    }
}

@MainActor
@Observable
final class ClipboardPanelModel {
    var query = ""
    var selected = 0
    var focusToken = 0

    func reset() {
        query = ""
        selected = 0
        focusToken += 1
    }
}

private struct ClipboardListView: View {
    @Bindable var model: ClipboardPanelModel
    let onChoose: (ClipboardHistory.Item) -> Void
    let onClose: () -> Void
    @FocusState private var searchFocused: Bool
    private var history: ClipboardHistory { .shared }

    var body: some View {
        let items = history.filtered(model.query)
        VStack(spacing: 0) {
            HStack(spacing: Theme.gapS) {
                Image(systemName: "magnifyingglass").foregroundStyle(.secondary)
                TextField("搜索剪贴板历史", text: $model.query)
                    .textFieldStyle(.plain)
                    .font(Theme.reading)
                    .focused($searchFocused)
                    .onSubmit { if items.indices.contains(model.selected) { onChoose(items[model.selected]) } }
                    .onKeyPress(.downArrow) { move(1, count: items.count); return .handled }
                    .onKeyPress(.upArrow) { move(-1, count: items.count); return .handled }
            }
            .padding(Theme.gapM)
            Divider()
            if items.isEmpty {
                Text(history.items.isEmpty
                     ? (ClipboardHistory.isEnabled ? "还没有记录。复制过的文字会出现在这里（最近 \(ClipboardHistory.limit) 条）。" : "剪贴板历史已在设置里关闭。")
                     : "没有找到包含「\(model.query)」的内容")
                    .font(Theme.body)
                    .foregroundStyle(.secondary)
                    .frame(maxWidth: .infinity, maxHeight: .infinity)
                    .padding()
            } else {
                ScrollViewReader { proxy in
                    ScrollView {
                        VStack(spacing: 2) {
                            ForEach(Array(items.enumerated()), id: \.element.id) { index, item in
                                row(item, index: index)
                                    .id(item.id)
                                    .onTapGesture { onChoose(item) }
                            }
                        }
                        .padding(Theme.gapXS)
                    }
                    .onChange(of: model.selected) { _, value in
                        if items.indices.contains(value) { proxy.scrollTo(items[value].id) }
                    }
                }
            }
            Divider()
            Text("↑↓ 选择 · 回车或点击粘贴到当前输入框 · Esc 关闭 · 只保存在内存里，退出即清空")
                .font(Theme.caption)
                .foregroundStyle(.tertiary)
                .padding(.vertical, 6)
        }
        .frame(maxWidth: .infinity, maxHeight: .infinity)
        .background(.regularMaterial)
        .onChange(of: model.query) { _, _ in model.selected = 0 }
        .onChange(of: model.focusToken, initial: true) { _, _ in
            DispatchQueue.main.async { searchFocused = true }
        }
    }

    private func move(_ delta: Int, count: Int) {
        guard count > 0 else { return }
        model.selected = min(max(0, model.selected + delta), count - 1)
    }

    private func row(_ item: ClipboardHistory.Item, index: Int) -> some View {
        let isSelected = index == model.selected
        return HStack(alignment: .top, spacing: Theme.gapS) {
            Text("\(index + 1)")
                .font(Theme.caption)
                .foregroundStyle(.tertiary)
                .frame(width: 16, alignment: .trailing)
            VStack(alignment: .leading, spacing: 2) {
                Text(item.text.trimmingCharacters(in: .whitespacesAndNewlines))
                    .font(Theme.body)
                    .lineLimit(2)
                    .frame(maxWidth: .infinity, alignment: .leading)
                Text([item.app, item.date.formatted(date: .omitted, time: .shortened), "\(item.text.count) 字"]
                        .compactMap { $0 }.joined(separator: " · "))
                    .font(Theme.caption)
                    .foregroundStyle(.secondary)
            }
        }
        .padding(.horizontal, Theme.gapS)
        .padding(.vertical, 6)
        .contentShape(Rectangle())
        .background(RoundedRectangle(cornerRadius: Theme.radiusSmall)
            .fill(isSelected ? Theme.accent.opacity(0.18) : Color.clear))
        .onHover { if $0 { model.selected = index } }
    }
}
